const byId = new Map<string, ProviderCatalogEntry>(PROVIDER_CATALOG.map((p) => [p.id, p]));

/** Look up a catalog entry by id, or undefined when unknown. */
export function getProvider(id: string | undefined | null): ProviderCatalogEntry | undefined {
  if (!id) return undefined;
  return byId.get(id);
}

