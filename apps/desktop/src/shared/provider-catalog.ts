/**
 * The manual provider catalog shown in the reviewer config. The user picks a
 * provider first (instead of relying only on key-prefix auto-detection); the
 * entry supplies the adapter, default endpoint and default model, and the
 * user only adds the API key (or none, for local servers).
 *
 * Every entry stores its FULL base URL prefix — the OpenAI adapter appends
 * `/chat/completions` (electron/reviewer/providers/openai.ts) and the live
 * model list appends `/models` (electron/model-list.ts) — so the prefix must
 * include the `/v1` (or provider-native) path.
 *
 * Adapters: 'openai' = OpenAI-compatible chat/completions, 'anthropic' =
 * Anthropic messages API, 'ollama' = Ollama /api/chat. Most providers are
 * OpenAI-compatible and reuse the existing 'openai' adapter.
 */

export type AdapterKind = 'openai' | 'anthropic' | 'ollama';

export interface ProviderCatalogEntry {
  /** Stable id persisted in settings (`reviewer.providerId`). */
  id: string;
  /** Human-friendly label for the picker. */
  name: string;
  /** Picker grouping. */
  group: 'cloud' | 'local' | 'custom';
  /** Which provider client adapter to build. */
  adapter: AdapterKind;
  /** Full base URL prefix ('' = user must supply one, custom only). */
  baseUrl: string;
  /** Suggested default model. */
  defaultModel: string;
  /** Offline model suggestions (the live list from the API is preferred). */
  models?: string[];
  /** Whether an API key is required. */
  auth: 'key' | 'none' | 'optional';
  /** Placeholder shown in the API key field. */
  keyHint?: string;
  /** Accuracy / usage note. */
  notes?: string;
}

